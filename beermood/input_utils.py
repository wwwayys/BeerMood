def input_int(message):
    """Запросить у пользователя неотрицательное целое число.

    Повторяет запрос до тех пор, пока не будет введено корректное значение.

    Args:
        message: Текст приглашения к вводу.

    Returns:
        Введённое пользователем неотрицательное целое число.
    """

    # Повторяем запрос, пока пользователь не введёт подходящее число
    while True:
        try:
            # Считываем строку и преобразуем её в целое число
            value = int(input(message))

            # Отрицательные значения для цены не подходят
            if value < 0:
                print("Введите число не меньше 0.")
                continue

            # Корректное число возвращаем из функции
            return value

        except ValueError:
            print("Ошибка: нужно ввести целое число.")
